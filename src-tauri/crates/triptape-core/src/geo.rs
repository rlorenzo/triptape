//! Spherical-earth geodesy helpers shared by clustering and privacy fuzzing.
//! Coordinates are `(lat, lon)` in degrees; distances in meters.

/// Mean earth radius (m).
pub const EARTH_RADIUS_M: f64 = 6_371_000.0;

/// Great-circle (haversine) distance in meters.
pub fn haversine_m(a: (f64, f64), b: (f64, f64)) -> f64 {
    let (a_lat, b_lat) = (a.0.to_radians(), b.0.to_radians());
    let (dlat, dlon) = ((b.0 - a.0).to_radians(), (b.1 - a.1).to_radians());
    let h = (dlat / 2.0).sin().powi(2) + a_lat.cos() * b_lat.cos() * (dlon / 2.0).sin().powi(2);
    2.0 * EARTH_RADIUS_M * h.sqrt().asin()
}

/// Initial bearing from `a` to `b` in degrees (0 = north, clockwise).
pub fn bearing_deg(a: (f64, f64), b: (f64, f64)) -> f64 {
    let (a_lat, b_lat, dlon) = (a.0.to_radians(), b.0.to_radians(), (b.1 - a.1).to_radians());
    let y = dlon.sin() * b_lat.cos();
    let x = a_lat.cos() * b_lat.sin() - a_lat.sin() * b_lat.cos() * dlon.cos();
    y.atan2(x).to_degrees()
}

/// Destination point `dist_m` from `origin` along `bearing_deg`.
pub fn project(origin: (f64, f64), bearing_deg: f64, dist_m: f64) -> (f64, f64) {
    let (lat, bearing) = (origin.0.to_radians(), bearing_deg.to_radians());
    let ang = dist_m / EARTH_RADIUS_M;
    let nlat = (lat.sin() * ang.cos() + lat.cos() * ang.sin() * bearing.cos()).asin();
    let nlon = origin.1.to_radians()
        + (bearing.sin() * ang.sin() * lat.cos()).atan2(ang.cos() - lat.sin() * nlat.sin());
    (nlat.to_degrees(), nlon.to_degrees())
}

/// Gazetteer of populated places (GeoNames cities15000, CC BY 4.0; see
/// `resources/gazetteer/ATTRIBUTION.md`), embedded at compile time.
/// Columns: name, country, latitude, longitude.
const GAZETTEER_TSV: &str = include_str!("../../../../resources/gazetteer/cities.tsv");

struct City {
    name: &'static str,
    country: &'static str,
    lat: f64,
    lon: f64,
}

fn gazetteer() -> &'static [City] {
    static CITIES: std::sync::OnceLock<Vec<City>> = std::sync::OnceLock::new();
    CITIES.get_or_init(|| {
        GAZETTEER_TSV
            .lines()
            .filter_map(|line| {
                let mut p = line.split('\t');
                Some(City {
                    name: p.next()?,
                    country: p.next()?,
                    lat: p.next()?.parse().ok()?,
                    lon: p.next()?.parse().ok()?,
                })
            })
            .collect()
    })
}

/// Land mask rasterized from Natural Earth 50m land polygons:
/// 0.05° cells (7200 × 3600), one bit per cell, row-major from
/// (-90, -180). Regenerated by `scripts/make-gazetteer.sh`.
const LAND_GRID: &[u8] = include_bytes!("../../../../resources/gazetteer/land-grid.bin");
const CELLS_PER_DEG: i64 = 20;
const GRID_W: i64 = 360 * CELLS_PER_DEG;
const GRID_H: i64 = 180 * CELLS_PER_DEG;
const COAST_BUFFER_CELLS: i64 = 2;

/// Whether `gps` is on land, allowing a `COAST_BUFFER_CELLS` (~11 km) coastal
/// buffer for shoreline GPS error, beaches, and harbors. Open water
/// fails: a cruise ship under way is not "in" the nearest port town,
/// so sea days honestly get no place name.
pub fn is_land(gps: (f64, f64)) -> bool {
    let col = ((gps.1 + 180.0) * CELLS_PER_DEG as f64) as i64;
    let row = ((gps.0 + 90.0) * CELLS_PER_DEG as f64) as i64;
    for dr in -COAST_BUFFER_CELLS..=COAST_BUFFER_CELLS {
        for dc in -COAST_BUFFER_CELLS..=COAST_BUFFER_CELLS {
            let r = row + dr;
            if !(0..GRID_H).contains(&r) {
                continue;
            }
            let idx = (r * GRID_W + (col + dc).rem_euclid(GRID_W)) as usize;
            if LAND_GRID[idx / 8] >> (idx % 8) & 1 == 1 {
                return true;
            }
        }
    }
    false
}

/// The name for `gps`: a nearby attraction beats the generic city.
/// `None` when nothing is close enough to name honestly (open water,
/// remote areas). This is the only place-name source in the app, backed
/// by the embedded gazetteers: no network reverse geocoding, ever.
pub fn place_name(gps: (f64, f64)) -> Option<String> {
    attraction_name(gps).or_else(|| city_name(gps))
}

/// Nearest populated place to `gps` within 100 km, as `City, Country`.
/// `None` when the point is on open water or no city is that close.
fn city_name(gps: (f64, f64)) -> Option<String> {
    if !is_land(gps) {
        return None;
    }
    nearest_within(gazetteer(), |c| (c.lat, c.lon), gps, 100_000.0)
        .map(|c| format!("{}, {}", c.name, c.country))
}

/// Named attractions (Wikidata, CC0): tourist attractions, parks,
/// museums, amusement parks, castles, zoos, temples, shrines, churches,
/// mosques with a notability floor
/// (Wikidata sitelinks). Columns: name, latitude, longitude.
const ATTRACTIONS_TSV: &str = include_str!("../../../../resources/gazetteer/attractions.tsv");

struct Attraction {
    name: &'static str,
    lat: f64,
    lon: f64,
}

fn attractions() -> &'static [Attraction] {
    static ITEMS: std::sync::OnceLock<Vec<Attraction>> = std::sync::OnceLock::new();
    ITEMS.get_or_init(|| {
        ATTRACTIONS_TSV
            .lines()
            .filter_map(|line| {
                let mut p = line.split('\t');
                Some(Attraction {
                    name: p.next()?,
                    lat: p.next()?.parse().ok()?,
                    lon: p.next()?.parse().ok()?,
                })
            })
            .collect()
    })
}

/// The attraction a photo was taken at, when one is within 2 km:
/// `Tokyo DisneySea` says more than `Urayasu, Japan`. `None` when no
/// known attraction is that close. The nearest wins: on the 2026 Japan to
/// Singapore trip, a notability weight or a 1 km radius for the tail of the
/// list changed none of the 72 chapter names.
fn attraction_name(gps: (f64, f64)) -> Option<String> {
    nearest_within(attractions(), |a| (a.lat, a.lon), gps, 2_000.0).map(|a| a.name.to_string())
}

/// The item nearest `gps` within `max_m`, by `coords` (`(lat, lon)`).
fn nearest_within<T>(
    items: &[T],
    coords: impl Fn(&T) -> (f64, f64),
    gps: (f64, f64),
    max_m: f64,
) -> Option<&T> {
    // Cheap bounding-box reject before the haversine. The latitude bound is
    // a fixed degree span; the longitude bound widens with latitude (a
    // degree of longitude shrinks by cos(lat)) and wraps across ±180°.
    let lat_deg = max_m / 111_000.0 + 0.5;
    let edge_lat = (gps.0.abs() + lat_deg).min(90.0).to_radians();
    let lon_deg = (lat_deg / edge_lat.cos().max(1e-6)).min(180.0);
    let mut best: Option<(&T, f64)> = None;
    for item in items {
        let (lat, lon) = coords(item);
        let dlon = (lon - gps.1).rem_euclid(360.0);
        if (lat - gps.0).abs() > lat_deg || dlon.min(360.0 - dlon) > lon_deg {
            continue;
        }
        let d = haversine_m(gps, (lat, lon));
        if d <= max_m && best.is_none_or(|(_, bd)| d < bd) {
            best = Some((item, d));
        }
    }
    best.map(|(item, _)| item)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn place_name_prefers_attraction_over_city() {
        assert_eq!(
            place_name((35.6267, 139.8881)).as_deref(),
            Some("Tokyo DisneySea")
        );
        // ~67 km from Alta: no attraction that close, so the city names it.
        assert_eq!(place_name((69.97, 21.5)).as_deref(), Some("Alta, Norway"));
    }

    #[test]
    fn towns_are_not_attractions() {
        // Town centers typed as tourist attractions in Wikidata keep the country.
        assert_eq!(
            place_name((51.39462, 8.57146)).as_deref(),
            Some("Brilon, Germany")
        );
        // The town filter spares archaeological sites and named-class items.
        assert_eq!(
            attraction_name((29.935, 52.89)).as_deref(),
            Some("Persepolis")
        );
        assert_eq!(
            attraction_name((55.66767, 37.66657)).as_deref(),
            Some("Kolomenskoye")
        );
    }

    #[test]
    fn attraction_name_finds_nearby_attraction() {
        // Inside Tokyo DisneySea: the attraction, not Urayasu.
        assert_eq!(
            attraction_name((35.6267, 139.8881)).as_deref(),
            Some("Tokyo DisneySea")
        );
        // Gardens by the Bay (Cloud Forest sits inside it).
        assert_eq!(
            attraction_name((1.2840, 103.8680)).as_deref(),
            Some("Gardens by the Bay")
        );
        // Hong Kong Disneyland.
        assert_eq!(
            attraction_name((22.3133, 114.0433)).as_deref(),
            Some("Hong Kong Disneyland")
        );
        // Jewel Changi Airport (a shopping center, but a destination).
        assert_eq!(
            attraction_name((1.3602, 103.9898)).as_deref(),
            Some("Jewel Changi Airport")
        );
    }

    #[test]
    fn temples_and_shrines_name_the_day() {
        // Kaminarimon gate: Sensō-ji, not the demolished Ryōunkaku tower
        // that used to sit in the list 600 m away.
        assert_eq!(
            place_name((35.7106, 139.7963)).as_deref(),
            Some("Sensō-ji Temple")
        );
        assert!(!ATTRACTIONS_TSV.contains("Ryōunkaku"));
        assert_eq!(
            place_name((35.3261, 139.5564)).as_deref(),
            Some("Tsurugaoka Hachimangū")
        );
        assert_eq!(
            place_name((35.3169, 139.5357)).as_deref(),
            Some("Kōtoku-in Temple")
        );
    }

    #[test]
    fn umbrella_resorts_yield_to_their_parks() {
        // The former coordinates of each resort row now name a park.
        for (gps, park) in [
            ((35.629722, 139.882778), "Tokyo Disneyland"),
            ((28.3722, -81.5494), "Epcot"),
            ((48.86872, 2.7818), "Disney Adventure World"),
        ] {
            assert_eq!(attraction_name(gps).as_deref(), Some(park));
        }
    }

    #[test]
    fn attraction_name_radius_holds_at_high_latitude() {
        // ~1.9 km east of Quttinirpaaq National Park at 82.2°N: 0.126° of
        // longitude.
        assert_eq!(
            attraction_name((82.216667, -72.0905)).as_deref(),
            Some("Quttinirpaaq National Park")
        );
        // ~3 km east: outside the 2 km radius.
        assert_eq!(attraction_name((82.216667, -72.0175)), None);
    }

    #[test]
    fn open_water_names_nothing() {
        // South China Sea (ship under way): coastal cities are within
        // 100 km, but no place is named.
        assert_eq!(place_name((2.221, 105.205)), None);
        assert_eq!(attraction_name((2.221, 105.205)), None);
        assert!(!is_land((16.564, 111.011)));
        // Singapore harbor counts as landfall.
        assert!(is_land((1.264, 103.840)));
    }

    #[test]
    fn is_land_handles_grid_edges() {
        // Both poles stay in bounds (Antarctica is land, the Arctic is not).
        assert!(is_land((-90.0, 0.0)));
        assert!(!is_land((90.0, 0.0)));
        // Land only across the antimeridian (Fiji's 180° edge): the buffer wraps.
        assert!(is_land((-17.075, -179.975)));
    }

    #[test]
    fn city_name_finds_nearest_city() {
        // Fushimi Inari, Kyoto.
        assert_eq!(
            city_name((34.9671, 135.7727)).as_deref(),
            Some("Kyoto, Japan")
        );
        // Marina Bay, Singapore.
        assert_eq!(
            city_name((1.2834, 103.8607)).as_deref(),
            Some("Singapore, Singapore")
        );
        // Middle of the Pacific: honestly unnamed.
        assert_eq!(city_name((0.0, -150.0)), None);
    }

    #[test]
    fn city_name_high_latitude_and_date_line() {
        // ~67 km west of Alta at 70°N: 1.77° of longitude, still in range.
        assert_eq!(city_name((69.97, 21.5)).as_deref(), Some("Alta, Norway"));
        // Across the antimeridian from Labasa (179.36°E), ~89 km away.
        assert_eq!(
            city_name((-16.4332, -179.8)).as_deref(),
            Some("Labasa, Fiji")
        );
    }

    #[test]
    fn haversine_known_distance() {
        // SF -> LA is ~559 km.
        let d = haversine_m((37.7749, -122.4194), (34.0522, -118.2437));
        assert!((d - 559_000.0).abs() < 5_000.0, "got {d}");
        assert_eq!(haversine_m((1.0, 2.0), (1.0, 2.0)), 0.0);
    }

    #[test]
    fn project_round_trips_bearing_and_distance() {
        let origin = (37.7749, -122.4194);
        let p = project(origin, 90.0, 1_000.0);
        assert!((haversine_m(origin, p) - 1_000.0).abs() < 1.0);
        assert!((bearing_deg(origin, p) - 90.0).abs() < 0.1);
    }
}
