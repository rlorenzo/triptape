//! Spherical-earth geodesy helpers shared by clustering and privacy fuzzing.
//! Coordinates are `(lat, lon)` in degrees; distances in meters.

/// Mean earth radius (m).
pub const EARTH_RADIUS_M: f64 = 6_371_000.0;

/// Great-circle (haversine) distance in meters.
pub fn haversine_m(a: (f64, f64), b: (f64, f64)) -> f64 {
    let (a_lat, b_lat) = (a.0.to_radians(), b.0.to_radians());
    let (dlat, dlon) = ((b.0 - a.0).to_radians(), (b.1 - a.1).to_radians());
    let h = (dlat / 2.0).sin().powi(2) + a_lat.cos() * b_lat.cos() * (dlon / 2.0).sin().powi(2);
    2.0 * EARTH_RADIUS_M * h.sqrt().asin()
}

/// Initial bearing from `a` to `b` in degrees (0 = north, clockwise).
pub fn bearing_deg(a: (f64, f64), b: (f64, f64)) -> f64 {
    let (a_lat, b_lat, dlon) = (a.0.to_radians(), b.0.to_radians(), (b.1 - a.1).to_radians());
    let y = dlon.sin() * b_lat.cos();
    let x = a_lat.cos() * b_lat.sin() - a_lat.sin() * b_lat.cos() * dlon.cos();
    y.atan2(x).to_degrees()
}

/// Destination point `dist_m` from `origin` along `bearing_deg`.
pub fn project(origin: (f64, f64), bearing_deg: f64, dist_m: f64) -> (f64, f64) {
    let (lat, bearing) = (origin.0.to_radians(), bearing_deg.to_radians());
    let ang = dist_m / EARTH_RADIUS_M;
    let nlat = (lat.sin() * ang.cos() + lat.cos() * ang.sin() * bearing.cos()).asin();
    let nlon = origin.1.to_radians()
        + (bearing.sin() * ang.sin() * lat.cos()).atan2(ang.cos() - lat.sin() * nlat.sin());
    (nlat.to_degrees(), nlon.to_degrees())
}

/// Gazetteer of populated places (GeoNames cities15000, CC BY 4.0; see
/// `resources/gazetteer/ATTRIBUTION.md`), embedded at compile time.
/// Columns: name, country, latitude, longitude.
const GAZETTEER_TSV: &str = include_str!("../../../../resources/gazetteer/cities.tsv");

struct City {
    name: &'static str,
    country: &'static str,
    lat: f64,
    lon: f64,
}

fn gazetteer() -> &'static [City] {
    static CITIES: std::sync::OnceLock<Vec<City>> = std::sync::OnceLock::new();
    CITIES.get_or_init(|| {
        GAZETTEER_TSV
            .lines()
            .filter_map(|line| {
                let mut p = line.split('\t');
                Some(City {
                    name: p.next()?,
                    country: p.next()?,
                    lat: p.next()?.parse().ok()?,
                    lon: p.next()?.parse().ok()?,
                })
            })
            .collect()
    })
}

/// The world's coastlines as closed polygon rings (Natural Earth 10m land,
/// simplified to about 400 m), for maps that draw land as shapes rather
/// than from the grid. Regenerated by `scripts/make-coast.sh`, which also
/// documents the format.
const COAST: &[u8] = include_bytes!("../../../../resources/gazetteer/coast.bin");

/// One closed coastline ring: an island, a continent, or an inland sea
/// inside one (fill with the even-odd rule).
#[derive(Debug, Clone, PartialEq)]
pub struct CoastRing {
    /// `lon, lat` in degrees; the last point joins the first.
    pub pts: Vec<(f32, f32)>,
    /// `(lon_min, lat_min, lon_max, lat_max)`.
    pub bbox: (f32, f32, f32, f32),
}

/// Every coastline ring, parsed once.
pub fn coastlines() -> &'static [CoastRing] {
    static RINGS: std::sync::OnceLock<Vec<CoastRing>> = std::sync::OnceLock::new();
    RINGS.get_or_init(|| parse_coast(COAST))
}

fn parse_coast(data: &[u8]) -> Vec<CoastRing> {
    const UNIT: f32 = 1000.0;
    let i32_at = |at: usize| {
        data.get(at..at + 4)
            .map(|b| i32::from_le_bytes([b[0], b[1], b[2], b[3]]))
    };
    let i16_at = |at: usize| {
        data.get(at..at + 2)
            .map(|b| i16::from_le_bytes([b[0], b[1]]))
    };
    let mut rings = vec![];
    if data.get(..4) != Some(b"TTC1".as_slice()) {
        return rings;
    }
    let count = i32_at(4).unwrap_or(0);
    let mut at = 8;
    for _ in 0..count {
        let (Some(n), Some(mut lon), Some(mut lat)) = (i32_at(at), i32_at(at + 4), i32_at(at + 8))
        else {
            break;
        };
        at += 12;
        let mut pts = vec![(lon as f32 / UNIT, lat as f32 / UNIT)];
        for _ in 1..n {
            let (Some(dx), Some(dy)) = (i16_at(at), i16_at(at + 2)) else {
                return rings;
            };
            at += 4;
            lon += i32::from(dx);
            lat += i32::from(dy);
            pts.push((lon as f32 / UNIT, lat as f32 / UNIT));
        }
        let mut bbox = (f32::MAX, f32::MAX, f32::MIN, f32::MIN);
        for p in &pts {
            bbox = (
                bbox.0.min(p.0),
                bbox.1.min(p.1),
                bbox.2.max(p.0),
                bbox.3.max(p.1),
            );
        }
        rings.push(CoastRing { pts, bbox });
    }
    rings
}

/// Land mask rasterized from Natural Earth 50m land polygons:
/// 0.05° cells (7200 × 3600), one bit per cell, row-major from
/// (-90, -180). Regenerated by `scripts/make-gazetteer.sh`.
const LAND_GRID: &[u8] = include_bytes!("../../../../resources/gazetteer/land-grid.bin");
const CELLS_PER_DEG: i64 = 20;
const GRID_W: i64 = 360 * CELLS_PER_DEG;
const GRID_H: i64 = 180 * CELLS_PER_DEG;
const COAST_BUFFER_CELLS: i64 = 2;

/// Whether `gps` is on land, allowing a `COAST_BUFFER_CELLS` (~11 km) coastal
/// buffer for shoreline GPS error, beaches, and harbors. Open water
/// fails: a cruise ship under way is not "in" the nearest port town,
/// so sea days honestly get no place name.
pub fn is_land(gps: (f64, f64)) -> bool {
    let col = ((gps.1 + 180.0) * CELLS_PER_DEG as f64) as i64;
    let row = ((gps.0 + 90.0) * CELLS_PER_DEG as f64) as i64;
    for dr in -COAST_BUFFER_CELLS..=COAST_BUFFER_CELLS {
        for dc in -COAST_BUFFER_CELLS..=COAST_BUFFER_CELLS {
            let r = row + dr;
            if !(0..GRID_H).contains(&r) {
                continue;
            }
            let idx = (r * GRID_W + (col + dc).rem_euclid(GRID_W)) as usize;
            if LAND_GRID[idx / 8] >> (idx % 8) & 1 == 1 {
                return true;
            }
        }
    }
    false
}

/// Land fraction around `gps` by bilinear blend of the four nearest raw
/// grid cells (no coastal buffer, unlike [`is_land`]): 0.0 open water to
/// 1.0 inland, with the coastline at 0.5. For drawing smooth shorelines.
pub fn land_fraction(gps: (f64, f64)) -> f32 {
    let fc = (gps.1 + 180.0) * CELLS_PER_DEG as f64 - 0.5;
    let fr = (gps.0 + 90.0) * CELLS_PER_DEG as f64 - 0.5;
    let (c0, r0) = (fc.floor(), fr.floor());
    let (tc, tr) = ((fc - c0) as f32, (fr - r0) as f32);
    let cell = |r: i64, c: i64| -> f32 {
        if !(0..GRID_H).contains(&r) {
            return 0.0;
        }
        let idx = (r * GRID_W + c.rem_euclid(GRID_W)) as usize;
        f32::from(LAND_GRID[idx / 8] >> (idx % 8) & 1)
    };
    let (r0, c0) = (r0 as i64, c0 as i64);
    let top = cell(r0, c0) * (1.0 - tc) + cell(r0, c0 + 1) * tc;
    let bottom = cell(r0 + 1, c0) * (1.0 - tc) + cell(r0 + 1, c0 + 1) * tc;
    top * (1.0 - tr) + bottom * tr
}

/// The land grid blurred (one pass of a 1-4-6-4-1 kernel in each axis,
/// sigma about 1 cell) into bytes, built on first use: 26 MB. Bilinear
/// lookups into it give coastlines without the raw grid's stair-steps when
/// zoomed in.
fn blurred_grid() -> &'static [u8] {
    static BLURRED: std::sync::OnceLock<Vec<u8>> = std::sync::OnceLock::new();
    BLURRED.get_or_init(|| {
        let (w, h) = (GRID_W as usize, GRID_H as usize);
        let mut cur: Vec<u8> = (0..w * h)
            .map(|i| {
                if LAND_GRID[i / 8] >> (i % 8) & 1 == 1 {
                    255
                } else {
                    0
                }
            })
            .collect();
        let mut tmp = vec![0u8; w * h];
        const K: [u32; 5] = [1, 4, 6, 4, 1];
        // One pass: sigma about one cell, enough to smooth stair-steps
        // without melting small islands.
        for _ in 0..1 {
            // Horizontal (wraps at the antimeridian).
            for y in 0..h {
                let row = &cur[y * w..(y + 1) * w];
                for x in 0..w {
                    let mut acc = 0;
                    for (k, wgt) in K.iter().enumerate() {
                        acc += wgt * u32::from(row[(x + w + k - 2) % w]);
                    }
                    tmp[y * w + x] = (acc / 16) as u8;
                }
            }
            // Vertical (clamped at the poles).
            for y in 0..h {
                for x in 0..w {
                    let mut acc = 0;
                    for (k, wgt) in K.iter().enumerate() {
                        let yy = (y + k).saturating_sub(2).min(h - 1);
                        acc += wgt * u32::from(tmp[yy * w + x]);
                    }
                    cur[y * w + x] = (acc / 16) as u8;
                }
            }
        }
        cur
    })
}

/// [`land_fraction`] from the blurred grid: smoother shorelines, 0.5 still
/// the coast. Builds a 26 MB table on first call.
pub fn land_fraction_smooth(gps: (f64, f64)) -> f32 {
    let grid = blurred_grid();
    let fc = (gps.1 + 180.0) * CELLS_PER_DEG as f64 - 0.5;
    let fr = (gps.0 + 90.0) * CELLS_PER_DEG as f64 - 0.5;
    let (c0, r0) = (fc.floor(), fr.floor());
    let (tc, tr) = ((fc - c0) as f32, (fr - r0) as f32);
    let cell = |r: i64, c: i64| -> f32 {
        if !(0..GRID_H).contains(&r) {
            return 0.0;
        }
        f32::from(grid[(r * GRID_W + c.rem_euclid(GRID_W)) as usize]) / 255.0
    };
    let (r0, c0) = (r0 as i64, c0 as i64);
    let top = cell(r0, c0) * (1.0 - tc) + cell(r0, c0 + 1) * tc;
    let bottom = cell(r0 + 1, c0) * (1.0 - tc) + cell(r0 + 1, c0 + 1) * tc;
    top * (1.0 - tr) + bottom * tr
}

/// The name for `gps`: a nearby attraction beats the generic city.
/// `None` when nothing is close enough to name honestly (open water,
/// remote areas). This is the only place-name source in the app, backed
/// by the embedded gazetteers: no network reverse geocoding, ever.
pub fn place_name(gps: (f64, f64)) -> Option<String> {
    attraction_name(gps).or_else(|| city_name(gps))
}

/// Nearest populated place to `gps` within 100 km, as `City, Country`.
/// `None` when the point is on open water or no city is that close.
pub fn city_name(gps: (f64, f64)) -> Option<String> {
    if !is_land(gps) {
        return None;
    }
    nearest_within(gazetteer(), |c| (c.lat, c.lon), gps, 100_000.0)
        .map(|c| format!("{}, {}", c.name, c.country))
}

/// `Kamakura, Japan` as `Kamakura`: a [`city_name`] without its country.
/// Any other name (`Flower Dome, Gardens by the Bay`) passes through.
pub fn without_country(name: &str) -> &str {
    static COUNTRIES: std::sync::OnceLock<std::collections::HashSet<&'static str>> =
        std::sync::OnceLock::new();
    let countries = COUNTRIES.get_or_init(|| gazetteer().iter().map(|c| c.country).collect());
    match name.rsplit_once(", ") {
        Some((town, country)) if countries.contains(country) => town,
        _ => name,
    }
}

/// Named attractions (Wikidata, CC0): tourist attractions, parks,
/// museums, amusement parks, castles, zoos, temples, shrines, churches,
/// mosques with a notability floor
/// (Wikidata sitelinks). Columns: name, latitude, longitude.
const ATTRACTIONS_TSV: &str = include_str!("../../../../resources/gazetteer/attractions.tsv");

struct Attraction {
    name: &'static str,
    lat: f64,
    lon: f64,
}

fn attractions() -> &'static [Attraction] {
    static ITEMS: std::sync::OnceLock<Vec<Attraction>> = std::sync::OnceLock::new();
    ITEMS.get_or_init(|| {
        ATTRACTIONS_TSV
            .lines()
            .filter_map(|line| {
                let mut p = line.split('\t');
                Some(Attraction {
                    name: p.next()?,
                    lat: p.next()?.parse().ok()?,
                    lon: p.next()?.parse().ok()?,
                })
            })
            .collect()
    })
}

/// The attraction a photo was taken at, when one is within 2 km:
/// `Tokyo DisneySea` says more than `Urayasu, Japan`. `None` when no
/// known attraction is that close. The nearest wins: on the 2026 Japan to
/// Singapore trip, a notability weight or a 1 km radius for the tail of the
/// list changed none of the 72 chapter names.
fn attraction_name(gps: (f64, f64)) -> Option<String> {
    attraction_within(gps, 2_000.0)
}

/// Attractions this close together are one place under several names.
const SAME_PLACE_M: f64 = 100.0;

/// The nearest known attraction within `max_m` of `gps`. Chapter names use
/// 2 km (a day centred near a place); captioning one photo needs to be much
/// closer, since a 2 km reach names whatever a walk passed by.
///
/// Wikidata files one spot under several names: Osaka Castle, Osaka Castle
/// Park and Ishiyama Hongan-ji (the temple the castle replaced) sit within
/// 20 m, and plain nearest picks among them by chance. Among names within
/// [`SAME_PLACE_M`] of the nearest, the best known wins (the list is most
/// notable first), and a name that contains it ("Osaka Castle Park" around
/// "Osaka Castle") wins over that: the grounds hold every shot there, the
/// building only some.
pub fn attraction_within(gps: (f64, f64), max_m: f64) -> Option<String> {
    let items = attractions();
    let nearest = nearest_within(items, |a| (a.lat, a.lon), gps, max_m)?;
    let reach = haversine_m(gps, (nearest.lat, nearest.lon)) + SAME_PLACE_M;
    let here: Vec<&Attraction> = items
        .iter()
        .filter(|a| haversine_m((a.lat, a.lon), (nearest.lat, nearest.lon)) <= SAME_PLACE_M)
        .filter(|a| haversine_m(gps, (a.lat, a.lon)) <= reach.min(max_m))
        .collect();
    let best = here.first().copied().unwrap_or(nearest);
    let area = here
        .iter()
        .filter(|a| a.name.len() > best.name.len() && a.name.contains(best.name))
        .min_by_key(|a| a.name.len());
    Some(area.map_or(best, |a| *a).name.to_string())
}

/// The item nearest `gps` within `max_m`, by `coords` (`(lat, lon)`).
fn nearest_within<T>(
    items: &[T],
    coords: impl Fn(&T) -> (f64, f64),
    gps: (f64, f64),
    max_m: f64,
) -> Option<&T> {
    // Cheap bounding-box reject before the haversine. The latitude bound is
    // a fixed degree span; the longitude bound widens with latitude (a
    // degree of longitude shrinks by cos(lat)) and wraps across ±180°.
    let lat_deg = max_m / 111_000.0 + 0.5;
    let edge_lat = (gps.0.abs() + lat_deg).min(90.0).to_radians();
    let lon_deg = (lat_deg / edge_lat.cos().max(1e-6)).min(180.0);
    let mut best: Option<(&T, f64)> = None;
    for item in items {
        let (lat, lon) = coords(item);
        let dlon = (lon - gps.1).rem_euclid(360.0);
        if (lat - gps.0).abs() > lat_deg || dlon.min(360.0 - dlon) > lon_deg {
            continue;
        }
        let d = haversine_m(gps, (lat, lon));
        if d <= max_m && best.is_none_or(|(_, bd)| d < bd) {
            best = Some((item, d));
        }
    }
    best.map(|(item, _)| item)
}

