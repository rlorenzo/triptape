    #[test]
    fn coastlines_load_and_hold_known_islands() {
        let rings = coastlines();
        assert!(rings.len() > 5000, "{}", rings.len());
        // Even-odd test of a point against every ring.
        let on_land = |lat: f32, lon: f32| {
            rings
                .iter()
                .filter(|r| {
                    let (x0, y0, x1, y1) = r.bbox;
                    lon >= x0 && lon <= x1 && lat >= y0 && lat <= y1
                })
                .map(|r| {
                    (0..r.pts.len())
                        .filter(|&i| {
                            let (a, b) = (r.pts[i], r.pts[(i + 1) % r.pts.len()]);
                            (a.1 > lat) != (b.1 > lat)
                                && lon < a.0 + (lat - a.1) / (b.1 - a.1) * (b.0 - a.0)
                        })
                        .count()
                })
                .sum::<usize>()
                % 2
                == 1
        };
        assert!(on_land(36.0, 138.0), "Honshu");
        assert!(on_land(33.38, 126.55), "Jeju");
        assert!(on_land(1.35, 103.82), "Singapore");
        assert!(!on_land(20.0, -150.0), "mid-Pacific");
        assert!(!on_land(34.3, 133.6), "Seto Inland Sea");
        // A truncated or foreign file yields nothing rather than a panic.
        assert!(parse_coast(b"nope").is_empty());
        assert!(parse_coast(&COAST[..COAST.len() / 2]).len() < rings.len());
    }

